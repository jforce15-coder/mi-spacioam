  window.SpacioI18n = {
    GTQ_RATE,
    MONTHS_ES: ["Ene", "Feb", "Mar", "Abr", "May", "Jun", "Jul", "Ago", "Sep", "Oct", "Nov", "Dic"],
    MONTHS_EN: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
    t(lang, key) { return (DICT[lang] && DICT[lang][key]) || (DICT.es[key]) || key; },
    monthLong(lang, m) { return MONTH_LONG[lang][m]; },
    // currency formatting; opts.decimals overrides
    money(amount, currency, opts) {
      opts = opts || {};
      const usd = amount;
      const val = currency === "GTQ" ? usd * GTQ_RATE : usd;
      const dec = opts.decimals != null ? opts.decimals : 0;
      const sym = currency === "GTQ" ? "Q" : "$";
      const neg = val < 0;
      const n = Math.abs(val).toLocaleString("en-US", { minimumFractionDigits: dec, maximumFractionDigits: dec });
      return (neg ? "−" : "") + sym + (currency === "GTQ" ? " " : "") + n;
    },
    moneyShort(amount, currency) {
      const val = (currency === "GTQ" ? amount * GTQ_RATE : amount);
      const sym = currency === "GTQ" ? "Q" : "$";
      const sp = currency === "GTQ" ? " " : "";
      const a = Math.abs(val);
      if (a >= 1000) return sym + sp + (val / 1000).toLocaleString("en-US", { maximumFractionDigits: a >= 10000 ? 0 : 1 }) + "k";
      return sym + sp + Math.round(val);
    },
    pct(v, dec) { return (v * 100).toLocaleString("en-US", { minimumFractionDigits: dec || 0, maximumFractionDigits: dec || 0 }) + "%"; },
    num(v) { return Math.round(v).toLocaleString("en-US"); },
  };
